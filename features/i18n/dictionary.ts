const sorted = [...dictionary].sort((a, b) => b[0].length - a[0].length);
export function translate(text: unknown, language: "kk" | "ru" = "kk"): string {
  const value = String(text ?? "");
  if (language !== "ru") return value;
  if (dictionary.has(value)) return dictionary.get(value)!;
  let out = value;
  const placeholders: string[] = [];
  for (const [kk, ru] of sorted) {
    if (out.includes(kk)) {
      const marker = `\u0001${placeholders.length}\u0002`;
      out = out.split(kk).join(marker);
      placeholders.push(ru);
    }
  }
  return out.replace(/\u0001(\d+)\u0002/g, (_, i) => placeholders[Number(i)]);
}
