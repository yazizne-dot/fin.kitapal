CREATE TABLE IF NOT EXISTS qarzhy.report_overrides (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES qarzhy.datasets(id) ON DELETE RESTRICT,
  report_family text NOT NULL CHECK (report_family IN ('pnl','balance','cashflow','sales','budget')),
  scope_id bigint NOT NULL REFERENCES qarzhy.report_scopes(id) ON DELETE RESTRICT,
  period_start date NOT NULL,
  period_end date NOT NULL,
  period_kind text NOT NULL CHECK (period_kind IN ('monthly','source_ytd','snapshot')),
  metric_id bigint NOT NULL REFERENCES qarzhy.report_metrics(id) ON DELETE RESTRICT,
  article_id bigint REFERENCES qarzhy.financial_articles(id) ON DELETE RESTRICT,
  channel_id bigint REFERENCES qarzhy.sales_channels(id) ON DELETE RESTRICT,
  source_value qarzhy.exact_number,
  value qarzhy.exact_number NOT NULL,
  revision bigint NOT NULL CHECK (revision>0),
  updated_by bigint NOT NULL REFERENCES qarzhy.users(id) ON DELETE RESTRICT,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (period_end>period_start),
  UNIQUE NULLS NOT DISTINCT (dataset_id,report_family,scope_id,period_start,period_end,
    period_kind,metric_id,article_id,channel_id)
);

CREATE TABLE IF NOT EXISTS qarzhy.report_override_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_id bigint NOT NULL REFERENCES qarzhy.datasets(id) ON DELETE RESTRICT,
  report_family text NOT NULL CHECK (report_family IN ('pnl','balance','cashflow','sales','budget')),
  scope_id bigint NOT NULL REFERENCES qarzhy.report_scopes(id) ON DELETE RESTRICT,
  period_start date NOT NULL,
  period_end date NOT NULL,
  period_kind text NOT NULL CHECK (period_kind IN ('monthly','source_ytd','snapshot')),
  metric_id bigint NOT NULL REFERENCES qarzhy.report_metrics(id) ON DELETE RESTRICT,
  article_id bigint REFERENCES qarzhy.financial_articles(id) ON DELETE RESTRICT,
  channel_id bigint REFERENCES qarzhy.sales_channels(id) ON DELETE RESTRICT,
  action text NOT NULL CHECK (action IN ('set','reset')),
  source_value qarzhy.exact_number,
  previous_value qarzhy.exact_number,
  next_value qarzhy.exact_number,
  revision bigint NOT NULL CHECK (revision>0),
  reason text NOT NULL CHECK (btrim(reason)<>''),
  author_id bigint NOT NULL REFERENCES qarzhy.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (period_end>period_start)
);
CREATE INDEX IF NOT EXISTS report_override_history_key_idx ON qarzhy.report_override_history
  (dataset_id,report_family,scope_id,period_start,metric_id,revision);

