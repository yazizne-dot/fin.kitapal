DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM qarzhy.schema_migrations WHERE version='0004_report_overrides') THEN
    RAISE EXCEPTION 'Expected report override migration 0004';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS qarzhy.portal_operations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES qarzhy.organizations(id) ON DELETE RESTRICT,
  source text NOT NULL CHECK (btrim(source)<>'' AND length(source)<=160),
  external_id text NOT NULL CHECK (btrim(external_id)<>'' AND length(external_id)<=160),
  occurred_on date NOT NULL,
  kind text NOT NULL CHECK (kind IN ('sale','return','purchase','expense','depreciation','tax',
    'receipt','supplier_payment','expense_payment','tax_payment','capital','loan','loan_payment','asset')),
  amount qarzhy.money NOT NULL CHECK (amount>0),
  cost qarzhy.money NOT NULL DEFAULT 0 CHECK (cost>=0),
  point text NOT NULL DEFAULT '',
  counterparty_label text NOT NULL DEFAULT '',
  document_label text NOT NULL CHECK (btrim(document_label)<>''),
  due_date date,
  article_label text NOT NULL DEFAULT '',
  document_id bigint UNIQUE REFERENCES qarzhy.documents(id) ON DELETE RESTRICT,
  financial_event_id bigint UNIQUE REFERENCES qarzhy.financial_events(id) ON DELETE RESTRICT,
  cash_movement_id bigint UNIQUE REFERENCES qarzhy.cash_movements(id) ON DELETE RESTRICT,
  created_by bigint NOT NULL REFERENCES qarzhy.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  version integer NOT NULL DEFAULT 1 CHECK (version>0),
  CHECK (financial_event_id IS NOT NULL OR cash_movement_id IS NOT NULL),
  UNIQUE (source,external_id)
);
CREATE INDEX IF NOT EXISTS portal_operations_org_date_idx
  ON qarzhy.portal_operations(organization_id,occurred_on,id);

INSERT INTO qarzhy.schema_migrations(version)
VALUES ('0005_portal_operations') ON CONFLICT (version) DO NOTHING;
COMMIT;
