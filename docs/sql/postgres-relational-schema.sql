-- Deferred integrity checks permit assembling a document within one transaction.
CREATE FUNCTION qarzhy.validate_document(p_id bigint) RETURNS void
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
DECLARE d qarzhy.documents; n bigint; total numeric;
BEGIN
 SELECT * INTO d FROM qarzhy.documents WHERE id=p_id FOR UPDATE;
 IF NOT FOUND THEN RETURN; END IF;
 SELECT count(*),coalesce(sum(line_amount),0) INTO n,total FROM qarzhy.document_lines WHERE document_id=p_id;
 IF d.input_mode='summary' AND n<>0 THEN RAISE EXCEPTION 'Summary document cannot have product lines'; END IF;
 IF EXISTS(SELECT 1 FROM qarzhy.document_lines l JOIN qarzhy.warehouses w ON w.id=l.warehouse_id WHERE l.document_id=p_id AND w.organization_id<>d.organization_id) THEN
  RAISE EXCEPTION 'Warehouse and document organizations differ';
 END IF;
 IF d.status IN ('posted','reversed') THEN
  IF d.total_amount<=0 THEN RAISE EXCEPTION 'Posted document amount must be positive'; END IF;
  IF d.counterparty_id IS NULL THEN RAISE EXCEPTION 'Posted document requires counterparty'; END IF;
  IF d.input_mode='itemized' AND (n=0 OR total<>d.total_amount) THEN
   RAISE EXCEPTION 'Posted itemized document requires lines matching its total';
  END IF;
  IF d.input_mode='itemized' AND EXISTS(SELECT 1 FROM qarzhy.document_lines WHERE document_id=p_id AND warehouse_id IS NULL) THEN
   RAISE EXCEPTION 'Posted product lines require warehouse';
  END IF;
 END IF;
END $$;
CREATE FUNCTION qarzhy.document_integrity() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 IF TG_TABLE_NAME='documents' THEN
  IF TG_OP<>'DELETE' THEN PERFORM qarzhy.validate_document(NEW.id); END IF;
 ELSE
  IF TG_OP<>'INSERT' THEN PERFORM qarzhy.validate_document(OLD.document_id); END IF;
  IF TG_OP<>'DELETE' THEN PERFORM qarzhy.validate_document(NEW.document_id); END IF;
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER documents_integrity AFTER INSERT OR UPDATE ON qarzhy.documents
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.document_integrity();
CREATE CONSTRAINT TRIGGER document_lines_integrity AFTER INSERT OR UPDATE OR DELETE ON qarzhy.document_lines
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.document_integrity();

-- Serialize mutations of small shared configuration tables, including absence checks.
CREATE FUNCTION qarzhy.serialize_configuration() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 EXECUTE format('LOCK TABLE qarzhy.%I IN SHARE ROW EXCLUSIVE MODE',TG_TABLE_NAME);
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER coverage_lock BEFORE INSERT OR UPDATE OR DELETE ON qarzhy.coverage_rules
 FOR EACH STATEMENT EXECUTE FUNCTION qarzhy.serialize_configuration();
CREATE TRIGGER articles_lock BEFORE INSERT OR UPDATE OR DELETE ON qarzhy.financial_articles
 FOR EACH STATEMENT EXECUTE FUNCTION qarzhy.serialize_configuration();
CREATE FUNCTION qarzhy.validate_configuration() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 IF TG_TABLE_NAME='financial_articles' THEN
  IF EXISTS(WITH RECURSIVE ancestors(id,parent_id) AS (
   SELECT id,parent_id FROM qarzhy.financial_articles WHERE id=NEW.parent_id
   UNION SELECT a.id,a.parent_id FROM qarzhy.financial_articles a JOIN ancestors p ON a.id=p.parent_id
  ) SELECT 1 FROM ancestors WHERE id=NEW.id) THEN RAISE EXCEPTION 'Article hierarchy cycle'; END IF;
 ELSE
  IF EXISTS(SELECT 1 FROM qarzhy.coverage_rules c WHERE c.id<>NEW.id AND c.scope_id=NEW.scope_id
   AND c.report_family=NEW.report_family
   AND (c.metric_id=NEW.metric_id OR c.metric_id IS NULL OR NEW.metric_id IS NULL)
   AND daterange(c.starts_on,c.ends_on,'[)') && daterange(NEW.starts_on,NEW.ends_on,'[)')) THEN
   RAISE EXCEPTION 'Report coverage overlaps another rule';
  END IF;
  IF NEW.opening_snapshot_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM qarzhy.balance_snapshots b
   WHERE b.id=NEW.opening_snapshot_id AND b.scope_id=NEW.scope_id AND b.dataset_id=NEW.dataset_id
    AND b.status='verified' AND b.as_of_date=NEW.starts_on) THEN
   RAISE EXCEPTION 'Coverage requires a verified opening snapshot of same dataset/scope/date';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER article_no_cycle BEFORE INSERT OR UPDATE ON qarzhy.financial_articles
 FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_configuration();
CREATE TRIGGER coverage_no_overlap BEFORE INSERT OR UPDATE ON qarzhy.coverage_rules
 FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_configuration();

-- Snapshot changes share the coverage lock and preserve existing opening references.
CREATE FUNCTION qarzhy.guard_opening_snapshot() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 LOCK TABLE qarzhy.coverage_rules IN SHARE ROW EXCLUSIVE MODE;
 IF EXISTS(SELECT 1 FROM qarzhy.coverage_rules c WHERE c.opening_snapshot_id=NEW.id
  AND (NEW.status<>'verified' OR NEW.scope_id<>c.scope_id
   OR NEW.dataset_id<>c.dataset_id OR NEW.as_of_date<>c.starts_on)) THEN
  RAISE EXCEPTION 'Snapshot is required as a verified opening snapshot by coverage';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER snapshot_preserve_coverage BEFORE UPDATE ON qarzhy.balance_snapshots
 FOR EACH ROW EXECUTE FUNCTION qarzhy.guard_opening_snapshot();

-- Transfers must have matching amounts, owners and dates, on different accounts.
CREATE FUNCTION qarzhy.validate_transfers() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM qarzhy.cash_transfers t
  JOIN qarzhy.cash_movements a ON a.id=t.outgoing_id
  JOIN qarzhy.cash_movements b ON b.id=t.incoming_id
  WHERE a.direction<>'out' OR b.direction<>'in' OR a.amount<>b.amount
   OR a.cash_account_id IS NULL OR b.cash_account_id IS NULL OR a.cash_account_id=b.cash_account_id
   OR a.dataset_id<>b.dataset_id OR a.occurred_on<>b.occurred_on
   OR a.organization_id IS DISTINCT FROM b.organization_id OR a.scope_id<>b.scope_id) THEN
  RAISE EXCEPTION 'Invalid internal cash transfer';
 END IF;
 IF EXISTS(SELECT 1 FROM qarzhy.cash_transfers a JOIN qarzhy.cash_transfers b
  ON a.outgoing_id=b.incoming_id OR a.incoming_id=b.outgoing_id) THEN
  RAISE EXCEPTION 'Cash movement cannot belong to multiple transfers';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER transfer_integrity AFTER INSERT OR UPDATE ON qarzhy.cash_transfers
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_transfers();
CREATE CONSTRAINT TRIGGER transfer_movements_integrity AFTER UPDATE ON qarzhy.cash_movements
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_transfers();

-- Lock referenced parents before changing allocations; aggregate checks run at COMMIT.
CREATE FUNCTION qarzhy.lock_settlement_parents() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
DECLARE old_document bigint; old_movement bigint; new_document bigint; new_movement bigint;
BEGIN
 IF TG_OP<>'INSERT' THEN old_document:=OLD.document_id; old_movement:=OLD.cash_movement_id; END IF;
 IF TG_OP<>'DELETE' THEN new_document:=NEW.document_id; new_movement:=NEW.cash_movement_id; END IF;
 PERFORM id FROM qarzhy.documents WHERE id IN(old_document,new_document) ORDER BY id FOR UPDATE;
 PERFORM id FROM qarzhy.cash_movements WHERE id IN(old_movement,new_movement) ORDER BY id FOR UPDATE;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER settlement_locks BEFORE INSERT OR UPDATE OR DELETE ON qarzhy.document_settlements
 FOR EACH ROW EXECUTE FUNCTION qarzhy.lock_settlement_parents();
CREATE FUNCTION qarzhy.validate_settlements() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM qarzhy.document_settlements s JOIN qarzhy.documents d ON d.id=s.document_id
  GROUP BY d.id,d.total_amount HAVING sum(s.amount)>d.total_amount) OR
 EXISTS(SELECT 1 FROM qarzhy.document_settlements s JOIN qarzhy.cash_movements m ON m.id=s.cash_movement_id
  GROUP BY m.id,m.amount HAVING sum(s.amount)>m.amount) THEN
  RAISE EXCEPTION 'Payment allocation exceeds document or movement amount';
 END IF;
 IF EXISTS(SELECT 1 FROM qarzhy.document_settlements s
  JOIN qarzhy.documents d ON d.id=s.document_id JOIN qarzhy.cash_movements m ON m.id=s.cash_movement_id
  WHERE d.status<>'posted' OR d.dataset_id<>m.dataset_id OR d.organization_id IS DISTINCT FROM m.organization_id
   OR d.counterparty_id IS DISTINCT FROM m.counterparty_id
   OR (d.kind IN ('sale','purchase_return') AND m.direction<>'in')
   OR (d.kind IN ('purchase','sale_return') AND m.direction<>'out')
   OR EXISTS(SELECT 1 FROM qarzhy.cash_transfers t WHERE m.id IN(t.outgoing_id,t.incoming_id))) THEN
  RAISE EXCEPTION 'Settlement document, counterparty, direction or organization mismatch';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER settlement_integrity AFTER INSERT OR UPDATE OR DELETE ON qarzhy.document_settlements
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_settlements();
CREATE CONSTRAINT TRIGGER settled_document_integrity AFTER UPDATE ON qarzhy.documents
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_settlements();
CREATE CONSTRAINT TRIGGER settled_movement_integrity AFTER UPDATE ON qarzhy.cash_movements
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_settlements();
CREATE CONSTRAINT TRIGGER settled_transfer_integrity AFTER INSERT OR UPDATE ON qarzhy.cash_transfers
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_settlements();

-- Common scope consistency and live-money precision (imports keep original decimals).
CREATE FUNCTION qarzhy.validate_fact_scope() RETURNS trigger
LANGUAGE plpgsql SET search_path=qarzhy,pg_catalog AS $$
DECLARE s qarzhy.report_scopes; k text;
BEGIN
 SELECT * INTO s FROM qarzhy.report_scopes WHERE id=NEW.scope_id;
 IF s.scope_type='organization' AND NEW.organization_id IS DISTINCT FROM s.organization_id THEN
  RAISE EXCEPTION 'Fact organization does not match report scope';
 END IF;
 IF NEW.import_batch_id IS NULL THEN
  SELECT kind INTO k FROM qarzhy.datasets WHERE id=NEW.dataset_id;
  IF k<>'live' OR NEW.organization_id IS NULL OR s.scope_type<>'organization' THEN
   RAISE EXCEPTION 'New facts require live dataset and organization scope';
  END IF;
  IF abs(NEW.amount)>=1000000000000000000 OR NEW.amount<>round(NEW.amount,2) THEN
   RAISE EXCEPTION 'Live money requires numeric(20,2) precision';
  END IF;
 END IF;
 IF TG_TABLE_NAME='financial_events' THEN
  IF NEW.document_id IS NOT NULL AND NOT EXISTS(
   SELECT 1 FROM qarzhy.documents d WHERE d.id=NEW.document_id AND d.organization_id=NEW.organization_id AND d.dataset_id=NEW.dataset_id) THEN
   RAISE EXCEPTION 'Financial event document context mismatch';
  END IF;
  IF NEW.import_batch_id IS NULL AND NEW.cost_amount IS NOT NULL AND (abs(NEW.cost_amount)>=1000000000000000000 OR NEW.cost_amount<>round(NEW.cost_amount,2)) THEN
   RAISE EXCEPTION 'Live cost requires numeric(20,2) precision';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER event_scope BEFORE INSERT OR UPDATE ON qarzhy.financial_events
 FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_fact_scope();
CREATE TRIGGER movement_scope BEFORE INSERT OR UPDATE ON qarzhy.cash_movements
 FOR EACH ROW EXECUTE FUNCTION qarzhy.validate_fact_scope();

