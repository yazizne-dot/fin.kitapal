-- Qarzhy: ұсынылған PostgreSQL 17+ схемасы. Бос базаға бір рет орындалады.
-- Бұл файл сайттың автоматты миграциясы емес. psql: ON_ERROR_STOP=1.
BEGIN;
CREATE SCHEMA qarzhy;
SET LOCAL search_path = qarzhy, pg_catalog;

CREATE TABLE organizations (
 id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username text NOT NULL CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,63}$'),
 name text NOT NULL CHECK (btrim(name) <> ''),
 role text NOT NULL CHECK (role IN ('admin','finance','employee')),
 org_id smallint REFERENCES organizations(id) ON DELETE RESTRICT,
 point text NOT NULL DEFAULT '',
 language text NOT NULL DEFAULT 'kk' CHECK (language IN ('kk','ru')),
 active boolean NOT NULL DEFAULT true,
 must_change_password boolean NOT NULL DEFAULT false,
 password_salt text NOT NULL CHECK (password_salt ~ '^[0-9a-f]{32}$'),
 password_hash text NOT NULL CHECK (password_hash ~ '^[0-9a-f]{128}$'),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_username_unique ON users(lower(username));
CREATE INDEX users_org_idx ON users(org_id);
-- Исходные книги: значения хранятся отдельными строками, не целым JSON.
CREATE TABLE source_workbooks (
 book text PRIMARY KEY CHECK (book IN ('pnl','balance','cashflow')),
 file_name text NOT NULL,
 sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
 imported_at timestamptz NOT NULL
);
CREATE TABLE source_sheets (
 book text NOT NULL REFERENCES source_workbooks(book) ON DELETE RESTRICT,
 name text NOT NULL,
 position integer NOT NULL CHECK (position > 0),
 dimension text,
 hidden boolean NOT NULL,
 PRIMARY KEY (book,name),
 UNIQUE (book,position)
);
CREATE TABLE source_cells (
 book text NOT NULL,
 sheet text NOT NULL,
 address text NOT NULL CHECK (address ~ '^[A-Z]+[1-9][0-9]*$'),
 value_type text NOT NULL CHECK (value_type IN ('number','string','boolean','null')),
 value_number numeric CHECK (value_number NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric)),
 value_text text,
 value_boolean boolean,
 formula text,
 has_formula boolean NOT NULL DEFAULT false,
 metadata jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(metadata) = 'object'),
 PRIMARY KEY (book,sheet,address),
 FOREIGN KEY (book,sheet) REFERENCES source_sheets(book,name) ON DELETE RESTRICT,
 CHECK (
  (value_type='number' AND value_number IS NOT NULL AND value_text IS NULL AND value_boolean IS NULL) OR
  (value_type='string' AND value_text IS NOT NULL AND value_number IS NULL AND value_boolean IS NULL) OR
  (value_type='boolean' AND value_boolean IS NOT NULL AND value_number IS NULL AND value_text IS NULL) OR
  (value_type='null' AND value_number IS NULL AND value_text IS NULL AND value_boolean IS NULL)
 ),
 CHECK (has_formula OR formula IS NULL)
);
CREATE TABLE sessions (
 token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at timestamptz NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (expires_at > created_at)
);
CREATE INDEX sessions_user_idx ON sessions(user_id);
CREATE INDEX sessions_expires_idx ON sessions(expires_at);
CREATE TABLE periods (
 month date PRIMARY KEY CHECK (extract(day FROM month) = 1),
 closed boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now(),
 updated_by bigint REFERENCES users(id) ON DELETE RESTRICT
);
CREATE INDEX periods_updated_by_idx ON periods(updated_by);
CREATE TABLE operations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source text NOT NULL CHECK (btrim(source) <> ''),
 external_id text NOT NULL CHECK (btrim(external_id) <> ''),
 date date NOT NULL,
 org_id smallint NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
 point text NOT NULL DEFAULT '', counterparty text NOT NULL DEFAULT '',
 document text NOT NULL CHECK (btrim(document) <> ''),
 kind text NOT NULL CHECK (kind IN ('sale','receipt','purchase','supplier_payment',
 'expense','expense_payment','depreciation','tax','tax_payment','capital',
 'loan','loan_payment','asset','transfer','return')),
 amount numeric(20,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
 cost numeric(20,2) NOT NULL DEFAULT 0 CHECK (cost >= 0 AND cost <> 'NaN'::numeric),
 due date, article text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT operations_source_external_unique UNIQUE(source,external_id)
);
CREATE INDEX operations_date_idx ON operations(date,id);
CREATE INDEX operations_org_date_idx ON operations(org_id,date);
CREATE TABLE plans (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date date NOT NULL,
 org_id smallint NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
 article text NOT NULL DEFAULT '',
 amount numeric(20,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
 direction text NOT NULL CHECK (direction IN ('in','out'))
);
CREATE INDEX plans_date_idx ON plans(date);
CREATE INDEX plans_org_date_idx ON plans(org_id,date);
CREATE TABLE budgets (
 month date NOT NULL CHECK (extract(day FROM month) = 1),
 org_id smallint NOT NULL REFERENCES organizations(id) ON DELETE RESTRICT,
 metric text NOT NULL CHECK (metric IN ('revenue','cost','opex','depreciation','tax')),
 amount numeric(20,2) NOT NULL CHECK (amount >= 0 AND amount <> 'NaN'::numeric),
 PRIMARY KEY(month,org_id,metric)
);
CREATE INDEX budgets_org_idx ON budgets(org_id);
CREATE TABLE employee_expenses (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 date date NOT NULL,
 amount numeric(20,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
 category text NOT NULL CHECK (btrim(category) <> ''),
 description text NOT NULL CHECK (btrim(description) <> ''),
 vendor text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','approved','rejected')),
 review_note text NOT NULL DEFAULT '',
 version integer NOT NULL DEFAULT 1 CHECK (version > 0),
 deleted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX expenses_user_idx ON employee_expenses(user_id);
CREATE INDEX expenses_user_date_idx ON employee_expenses(user_id,date,id) WHERE deleted_at IS NULL;
CREATE INDEX expenses_status_idx ON employee_expenses(status,date,id) WHERE deleted_at IS NULL;
CREATE TABLE financial_entries (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 date date NOT NULL,
 kind text NOT NULL CHECK (kind IN ('revenue','cost','opex','otherExpense','taxes',
 'bonuses','otherIncome','cash_in','cash_out')),
 amount numeric(20,2) NOT NULL CHECK (amount > 0 AND amount <> 'NaN'::numeric),
 label text NOT NULL CHECK (btrim(label) <> ''), note text NOT NULL DEFAULT '',
 cash_effect boolean NOT NULL DEFAULT false,
 expense_id bigint UNIQUE REFERENCES employee_expenses(id) ON DELETE RESTRICT,
 active boolean NOT NULL DEFAULT true,
 author_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (expense_id IS NULL OR (kind = 'opex' AND cash_effect))
);
CREATE INDEX entries_active_date_idx ON financial_entries(date,id) WHERE active;
CREATE INDEX entries_author_idx ON financial_entries(author_id);
CREATE TABLE financial_overrides (
 book text NOT NULL, sheet text NOT NULL, cell text NOT NULL,
 value numeric NOT NULL CHECK (value NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric)),
 reason text NOT NULL CHECK (btrim(reason) <> ''),
 base_hash text NOT NULL,
 author_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 updated_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(book,sheet,cell)
);
CREATE INDEX overrides_author_idx ON financial_overrides(author_id);
CREATE TABLE financial_state (
 id smallint PRIMARY KEY CHECK (id = 1),
 revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0)
);
INSERT INTO financial_state(id,revision) VALUES (1,0);
CREATE TABLE audit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 at timestamptz NOT NULL DEFAULT now(),
 author_id bigint REFERENCES users(id) ON DELETE SET NULL,
 author_name text NOT NULL,
 action text NOT NULL CHECK (btrim(action) <> ''),
 detail text NOT NULL DEFAULT '', detail_json jsonb
);
CREATE INDEX audit_author_idx ON audit(author_id);
CREATE TABLE schema_migrations (
 version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()
);

-- SHARE кесте құлпы: ай жоқ болса да, кезеңді қатар жабудан қорғайды.
-- INSERT/UPDATE/DELETE кезінде ескі және жаңа ай тексеріледі.
-- Жабу periods кестесіне кәдімгі INSERT/UPDATE арқылы жасалады.
-- READ COMMITTED және қысқа транзакциялар; жоғары жүктемеде айлық құлыпқа ауыстыруға болады.
CREATE FUNCTION qarzhy.guard_period() RETURNS trigger
LANGUAGE plpgsql SET search_path = qarzhy, pg_catalog AS $$
DECLARE old_month date; new_month date;
BEGIN
 LOCK TABLE qarzhy.periods IN SHARE MODE;
 IF TG_OP <> 'INSERT' THEN
  IF TG_TABLE_NAME = 'budgets' THEN old_month := OLD.month;
  ELSE old_month := date_trunc('month',OLD.date)::date; END IF;
 END IF;
 IF TG_OP <> 'DELETE' THEN
  IF TG_TABLE_NAME = 'budgets' THEN new_month := NEW.month;
  ELSE new_month := date_trunc('month',NEW.date)::date; END IF;
 END IF;
 IF EXISTS (SELECT 1 FROM qarzhy.periods WHERE closed AND month IN (old_month,new_month)) THEN
  RAISE EXCEPTION 'Кезең жабық' USING ERRCODE = '23514';
 END IF;
 IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER operations_period_guard BEFORE INSERT OR UPDATE OR DELETE ON operations
 FOR EACH ROW EXECUTE FUNCTION qarzhy.guard_period();
CREATE TRIGGER entries_period_guard BEFORE INSERT OR UPDATE OR DELETE ON financial_entries
 FOR EACH ROW EXECUTE FUNCTION qarzhy.guard_period();
CREATE TRIGGER budgets_period_guard BEFORE INSERT OR UPDATE OR DELETE ON budgets
 FOR EACH ROW EXECUTE FUNCTION qarzhy.guard_period();

-- Қосымша revision-ды қайта өсірмейді: оны осы триггер атқарады.
CREATE FUNCTION qarzhy.bump_revision() RETURNS trigger
LANGUAGE plpgsql SET search_path = qarzhy, pg_catalog AS $$
BEGIN
 UPDATE qarzhy.financial_state SET revision = revision + 1 WHERE id = 1;
 RETURN NULL;
END $$;
CREATE TRIGGER entries_revision AFTER INSERT OR UPDATE OR DELETE ON financial_entries
 FOR EACH STATEMENT EXECUTE FUNCTION qarzhy.bump_revision();
CREATE TRIGGER overrides_revision AFTER INSERT OR UPDATE OR DELETE ON financial_overrides
 FOR EACH STATEMENT EXECUTE FUNCTION qarzhy.bump_revision();

